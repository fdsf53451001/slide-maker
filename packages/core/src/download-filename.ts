/**
 * 下載檔名的清洗規則。**唯一一份**，前後端共用。
 *
 * 兩類呼叫端：伺服器的整份匯出（`pptx`／`pdf`／`png.zip`／`slide-project`／`outline.md`）與
 * 單頁 PNG，以及編輯器精靈裡那顆在瀏覽器就地產檔的「下載大綱」。同一台伺服器上 `pptx` 與
 * `outline.md` 的檔名規則若各留一份，遲早各自漂移成兩套。也因此它**不能**相依 `node:path`
 * ——core 是前端也要 bundle 的套件。
 */

/**
 * 專案名稱洗成可以當檔名的字串；洗光了就退回 `presentation`。
 *
 * 舊版先過一次 node 的 `basename()` 再套底下這條正則。拿掉它之後的行為差異，完整列出：
 *
 * - `/` 之前的段落從**被丟棄**變成以 `-` 併入：`a/b` 舊版給 `b`，現在給 `a-b`。這是下載檔名
 *   而不是磁碟路徑，保留使用者原本寫的整個名字比截掉一半更貼近他的意圖。
 * - 少數原本會被洗光而退回 `presentation` 的名字現在拿得到名字：`基隆/` 舊版 `basename()`
 *   回空字串、最後變 `presentation`，現在是 `基隆`。
 * - `\` 只在 Windows 上與舊版有差（POSIX 的 `basename` 不把它當分隔符），伺服器不跑 Windows。
 * - 輸出**仍然不可能含路徑分隔符**：`/` 與 `\` 都不在 `\p{L}\p{N}._-` 裡，一律被洗成 `-`。
 *
 * 開頭的點必須剝掉，這是拿掉 `basename()` **引進的迴歸**而不是既有行為：專案名 `./設計`
 * 會洗成 `.-設計`，而 `.` 開頭的檔案在 macOS／Linux 上是隱藏檔——使用者下載完在資料夾裡
 * 根本看不到它（舊版經過 `basename()` 得到的是 `設計`）。`../../etc/passwd` 同理，剝掉之後
 * 是 `etc-passwd`。只剝開頭：結尾的點不會讓檔案消失，而副檔名一律接在後面。
 */
export function safeProjectFilename(name: string): string {
  return (
    name
      .replace(/[^\p{L}\p{N}._-]+/gu, "-")
      // 開頭連 `-` 帶 `.` 一起剝：`-` 是原本就有的（純美觀），`.` 是上面那條隱藏檔的理由。
      .replace(/^[-.]+|-+$/g, "") || "presentation"
  );
}
